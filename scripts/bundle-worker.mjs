// Bundles the discovery-worker Edge Function into a single self-contained module.
//
// Why: the Supabase edge-runtime (Deno) does NOT honor `sloppy-imports` at runtime, so it can't
// resolve the extensionless `@/...` / relative imports that the shared `src/` core uses (boot error
// "Module not found: .../pipeline"). We keep ONE source of truth (`worker.ts` importing `@/...`) and
// bundle it here into `index.ts` (the deployed entry): all local/pure code is inlined, and only the
// Deno-native specifiers (`jsr:` / `npm:` / `node:`) stay external for the runtime to resolve.
//
// Run:  yarn build:functions   (then `supabase functions deploy discovery-worker --no-verify-jwt`)

import * as esbuild from 'esbuild'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const fnDir = path.join(root, 'supabase/functions/discovery-worker')

await esbuild.build({
  entryPoints: [path.join(fnDir, 'worker.ts')],
  outfile: path.join(fnDir, 'index.ts'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'esnext',
  // Leave the runtime-provided specifiers alone; inline everything else (our pure `src/` core).
  external: ['jsr:*', 'npm:*', 'node:*', 'https://*'],
  alias: { '@': path.join(root, 'src') },
  legalComments: 'none',
  banner: {
    js: '// GENERATED by scripts/bundle-worker.mjs — DO NOT EDIT. Edit worker.ts and run `yarn build:functions`.',
  },
  logLevel: 'info',
})

console.log('✓ bundled supabase/functions/discovery-worker/index.ts')
